/**
 * دریافت اطلاعات کامل یک وزن با کد پوشه
 */
export function getMeterByCode(code: number): MeterInfo {
  const rawText = FOLDER_METERS[code];
  if (!rawText) {
    return {
      code,
      pattern: `وزن ناشناخته (کد ${code})`,
      name: "کد در جدول ثبت نشده است",
    };
  }

  // جدا کردن نام بحر داخل پرانتز اگر موجود باشد
  const match = rawText.match(/^(.*?)(?:\s*\((.*?)\))?$/);
  const pattern = (match ? match[1] : rawText).trim();
  const bahr = match && match[2] ? match[2].trim() : extractBahrFromPattern(pattern);

  const example = FAMOUS_EXAMPLES[code];

  return {
    code,
    pattern,
    name: rawText,
    bahr,
    syllables: example?.syllables || generateSyllableGuide(pattern),
    example: example ? {
      poet: example.poet,
      verse1: example.verse1,
      verse2: example.verse2,
    } : undefined,
  };
}

/**
 * تشخیص نام بحر تقریبی از روی واژگان تقطیع
 */
function extractBahrFromPattern(pattern: string): string {
  if (pattern.includes("مفاعیلن")) return "بحر هزج";
  if (pattern.includes("فاعلاتن")) return "بحر رمل";
  if (pattern.includes("مستفعلن")) return "بحر رجز";
  if (pattern.includes("فعولن")) return "بحر متقارب";
  if (pattern.includes("مفتعلن")) return "بحر منسرح / سریع";
  if (pattern.includes("مفاعلن")) return "بحر مجتث / هزج";
  if (pattern.includes("متفاعلن")) return "بحر کامل";
  if (pattern.includes("فعلاتن")) return "بحر رمل مخبون";
  if (pattern.includes("مفعول")) return "بحر مضارع / هزج اخرب";
  return "اوزان عروضی فارسی";
}

/**
 * تولید تقطیع نشانه‌ای فرضی برای هجاها بر اساس ارکان
 */
function generateSyllableGuide(pattern: string): string {
  const tokenMap: Record<string, string> = {
    "فاعلاتن": "— U — —",
    "فاعلن": "— U —",
    "فاعلات": "— U — U",
    "فاع": "—",
    "فع": "—",
    "فعلن": "— —",
    "مفاعیلن": "U — — —",
    "مفاعیل": "U — — U",
    "فعولن": "U — —",
    "فعول": "U — U",
    "مستفعلن": "— — U —",
    "مستفعل": "— — U",
    "مفتعلن": "— U U —",
    "مفاعلن": "U — U —",
    "فعلاتن": "U U — —",
    "مفعولن": "— — —",
    "مفعول": "— — U",
    "متفاعلن": "U U — U —",
    "متفاعلتن": "U U — U U —",
    "مفاعلتن": "U — U U —",
  };

  const parts = pattern.split(/\s+/);
  const syllables = parts
    .map(p => tokenMap[p] || (p.endsWith("ن") ? "—" : "U"))
    .join(" / ");
  
  return syllables;
}
